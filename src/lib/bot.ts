function normalize(s: string) { return s.toLowerCase().replace(/ё/g, "е"); }

/** Быстрый ответ из базы знаний, null — если не нашли. */
export function faqAnswer(text: string): string | null {
  const t = normalize(text);
  let best: { score: number; answer: string } | null = null;
  for (const f of FAQ) {
    const score = f.keys.reduce((n, k) => (t.includes(normalize(k)) ? n + k.length : n), 0);
    if (score > 0 && (!best || score > best.score)) best = { score, answer: f.answer };
  }
  return best?.answer ?? null;
}

