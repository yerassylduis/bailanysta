export async function botReply(text: string): Promise<string> {
  const quick = faqAnswer(text);
  if (quick) return quick;
  if (!process.env.ANTHROPIC_API_KEY) return FALLBACK;
  try {
    const client = new Anthropic({ timeout: 15_000, maxRetries: 0 });
    const res = await client.messages.create({
      model: "claude-opus-5", max_tokens: 400, system: SYSTEM,
      messages: [{ role: "user", content: text }],
      output_config: { effort: "low" },
    });
    if (res.stop_reason === "refusal") return FALLBACK;
    const out = res.content.filter((b) => b.type === "text").map((b) => b.text).join("\n").trim();
    return out || FALLBACK;
  } catch (e) {
    console.error("[bot]", e instanceof Error ? e.message : e);
    return FALLBACK;
  }
}
